#!/usr/bin/env python3
"""
build_search.py - Generates js/posts-data.js for mindsoap search index.
Scans all post HTML files in 202* directories and extracts metadata.
"""

import os
import glob
import re
import json

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
POSTS_PATTERN = os.path.join(SCRIPT_DIR, "202*", "*.html")
ARCHIVE_PATH = os.path.join(SCRIPT_DIR, "archive.html")
OUTPUT_JS = os.path.join(SCRIPT_DIR, "js", "posts-data.js")

def parse_archive_categories():
    """Extract category mappings from archive.html if available."""
    categories = {}
    if not os.path.exists(ARCHIVE_PATH):
        return categories

    with open(ARCHIVE_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    # Find category blocks like <p><b>Category</b> ... </p>
    cat_blocks = re.findall(r'<p><b>(.*?)</b>(.*?)</p>', content, re.DOTALL)
    for cat_name, block in cat_blocks:
        cat_name = cat_name.strip()
        if cat_name.lower() in ["years", "년도"]:
            continue
        links = re.findall(r'href=[\"\'](/202[0-9]/[^\"\']+\.html)[\"\']', block)
        for link in links:
            categories[link] = cat_name

    return categories

def clean_html(raw_html):
    """Remove HTML tags and extra whitespace."""
    clean = re.sub(r'<script.*?</script>', '', raw_html, flags=re.DOTALL)
    clean = re.sub(r'<style.*?</style>', '', clean, flags=re.DOTALL)
    clean = re.sub(r'<[^<]+?>', ' ', clean)
    clean = re.sub(r'&[a-zA-Z0-9#]+;', ' ', clean)
    clean = re.sub(r'\s+', ' ', clean)
    return clean.strip()

def extract_post_data(file_path, categories):
    with open(file_path, "r", encoding="utf-8") as f:
        html = f.read()

    rel_path = "/" + os.path.relpath(file_path, SCRIPT_DIR)

    # 1. Date from filename (YYYY-MM-DD)
    fname = os.path.basename(file_path)
    date_match = re.search(r'(\d{4}-\d{2}-\d{2})', fname)
    date = date_match.group(1) if date_match else ""

    # 2. Title from <title> or <h1>
    title_match = re.search(r'<title>(.*?)</title>', html, re.IGNORECASE | re.DOTALL)
    if title_match:
        title = title_match.group(1).strip()
        title = re.sub(r'\s*[—–-]\s*mindsoap.*$', '', title).strip()
    else:
        h1_match = re.search(r'<h1[^>]*>(.*?)</h1>', html, re.IGNORECASE | re.DOTALL)
        if h1_match:
            title = clean_html(h1_match.group(1))
            title = re.sub(r'\d{4}-\d{2}-\d{2}', '', title).strip()
        else:
            title = fname.replace(".html", "")

    # 3. Description from <meta name="description">
    desc_match = re.search(r'<meta\s+name=[\"\']description[\"\']\s+content=[\"\'](.*?)[\"\']', html, re.IGNORECASE)
    desc = desc_match.group(1).strip() if desc_match else ""

    # 4. Category
    category = categories.get(rel_path, "")
    if not category:
        # Fallback category from badge or default
        badge_match = re.search(r'class=[\"\']badge-category[\"\']>([^<]+)<', html)
        if badge_match:
            category = badge_match.group(1).strip()
        else:
            category = "post"

    # 5. Body excerpt for rich keyword search
    body_match = re.search(r'<div class=[\"\']post[\"\']>(.*?)</div>', html, re.DOTALL)
    if body_match:
        body_text = clean_html(body_match.group(1))[:300]
    else:
        body_text = clean_html(html)[:300]

    return {
        "title": title,
        "date": date,
        "url": rel_path,
        "category": category,
        "desc": desc,
        "body": body_text
    }

def main():
    categories = parse_archive_categories()
    files = sorted(glob.glob(POSTS_PATTERN), reverse=True)

    posts = []
    for f in files:
        post = extract_post_data(f, categories)
        posts.append(post)

    # Sort posts by date descending
    posts.sort(key=lambda x: (x["date"], x["url"]), reverse=True)

    os.makedirs(os.path.dirname(OUTPUT_JS), exist_ok=True)
    with open(OUTPUT_JS, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by build_search.py - do not edit directly */\n")
        f.write("window.MINDSOAP_POSTS = ")
        json.dump(posts, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Successfully generated {OUTPUT_JS} with {len(posts)} posts.")

if __name__ == "__main__":
    main()
